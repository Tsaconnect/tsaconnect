// services/serviceListingApi.ts
// API calls for the three service types' listing config: per-service profile
// (fees, slot config, policies, coverage), the order-type menu, and booking-type
// availability windows + computed slots. Reads are public; writes require the
// owning merchant's auth token. See the Go backend service_* handlers.
import AsyncStorage from '@react-native-async-storage/async-storage';
import { API_BASE_URL } from '../constants/api/config';
import type { SchemaFieldType } from '@/utils/schemaFields';

export interface ApiResponse<T = any> {
  success: boolean;
  message?: string;
  data?: T;
}

// Unified booking-engine config dimensions (mirror the Go enums).
export type BookingType = 'instant' | 'request';
export type PricingMethod = 'fixed' | 'on_request';

// The booking form and category listing fields share one field vocabulary.
export type BookingFieldType = SchemaFieldType;

export interface BookingField {
  key: string;
  type: BookingFieldType;
  label: string;
  group?: string;
  required: boolean;
  options?: string[];
  custom?: boolean;
}

export interface BookingFieldConfig {
  fields: BookingField[];
}

export interface ServiceProfile {
  id?: string;
  productId: string;
  accessFeeUsd: number;
  calloutFeeUsd: number;
  slotDurationMinutes: number;
  maxCapacityPerSlot: number;
  serviceAddress?: string;
  coverageArea?: string;
  operatingCompany?: string;
  // IANA zone the availability windows are written in. The server defaults it
  // to Africa/Lagos and rejects an unloadable name; there is no picker yet, so
  // in practice every listing uses the default.
  timezone?: string;
  cancellationPolicy?: string;
  reschedulePolicy?: string;
  refundPolicy?: string;
  bookingRules?: string;
  // Booking-engine config (Phase 1: instant/fixed defaults).
  bookingType?: BookingType;
  pricingMethod?: PricingMethod;
  bookingFeeUsd?: number;
  fieldConfig?: BookingFieldConfig | null;
  // What the price buys ('per_seat', …); '' on listings that predate units.
  priceUnit?: string;
}

// The customer form schema, generated by the server from the merchant's config.
export interface BookingFormSchema {
  productId: string;
  serviceType: 'contact' | 'order' | 'booking';
  bookingType: BookingType;
  pricingMethod: PricingMethod;
  // The category's booking mode. In 'quantity' mode the buyer picks a quantity
  // up to maxQuantity, and chargesPerUnit says the price is paid per unit.
  bookingMode?: 'slot' | 'date_range' | 'quantity';
  priceUnit?: string;
  chargesPerUnit?: boolean;
  maxQuantity?: number;
  fields: BookingField[];
  policies: {
    cancellation?: string;
    reschedule?: string;
    refund?: string;
    rules?: string;
  };
}

// A catalog entry the merchant builder toggles on/off.
export interface BookingCatalogField {
  key: string;
  type: BookingFieldType;
  label: string;
  group: string;
}

export interface ServiceMenuItem {
  id: string;
  productId: string;
  name: string;
  description?: string;
  priceUsd: number;
  imageUrl?: string;
  isAvailable: boolean;
  sortOrder: number;
}

export interface AvailabilityWindow {
  dayOfWeek: number; // 0=Sun … 6=Sat
  startTime: string; // "HH:MM"
  endTime: string;
}

export interface OpenSlot {
  start: string; // RFC3339
  end: string;
  capacity: number; // 0 = unlimited
  booked: number;
  remaining: number; // -1 = unlimited
}

export const WEEKDAY_LABELS = ['Sun', 'Mon', 'Tue', 'Wed', 'Thu', 'Fri', 'Sat'];

async function authHeaders(): Promise<Record<string, string>> {
  const token = await AsyncStorage.getItem('authToken');
  return {
    'Content-Type': 'application/json',
    ...(token ? { Authorization: `Bearer ${token}` } : {}),
  };
}

async function handleResponse<T>(response: Response): Promise<ApiResponse<T>> {
  let data: any;
  try {
    data = await response.json();
  } catch {
    return { success: false, message: `HTTP ${response.status}` };
  }
  if (!response.ok) {
    return { success: false, message: data.message || `Request failed (${response.status})` };
  }
  return { success: true, ...data };
}

// ---------- profile ----------

export async function getServiceProfile(productId: string): Promise<ApiResponse<ServiceProfile>> {
  try {
    const res = await fetch(`${API_BASE_URL}/services/${productId}/profile`, { method: 'GET' });
    return await handleResponse(res);
  } catch (e: any) {
    return { success: false, message: e.message || 'Failed to load service profile' };
  }
}

export async function upsertServiceProfile(
  productId: string,
  profile: Partial<ServiceProfile>
): Promise<ApiResponse<ServiceProfile>> {
  try {
    const headers = await authHeaders();
    const res = await fetch(`${API_BASE_URL}/services/${productId}/profile`, {
      method: 'PUT',
      headers,
      body: JSON.stringify(profile),
    });
    return await handleResponse(res);
  } catch (e: any) {
    return { success: false, message: e.message || 'Failed to save service profile' };
  }
}

